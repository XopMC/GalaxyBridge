import AppKit
import Foundation

@main enum ClipboardConversionWorkerSpec {
    final class State: @unchecked Sendable {
        let lock = NSLock()
        var encoded: [Int] = []
        var results: [MacClipboardConversionWorker.Result] = []
        func record(_ value: MacClipboardConversionWorker.Result) { lock.withLock { results.append(value) } }
    }
    static func main() {
        eligibilityPrecedesImageWork()
        onlyLatestPendingSnapshotIsConverted()
        invalidOccurrenceSupersedesActiveWork()
        queuedCompletionHasAnAdmissionFence()
        shutdownDropsActiveAndPendingWork()
        imagePixelsAndPayloadPolicySurviveConversion()
        print("PASS clipboard conversion: early eligibility, bounded latest pending, occurrence fences, shutdown, exact pixels and PNG policy")
    }
    static func snapshot(_ occurrence: Int, types: [String] = ["public.tiff"]) -> MacClipboardSnapshot {
        .init(occurrence: occurrence, pasteboardTypes: types, text: "fallback", image: .encoded(Data([UInt8(occurrence)])))
    }
    static func eligibilityPrecedesImageWork() {
        let queue = DispatchQueue(label: "clipboard.spec.eligibility"), state = State()
        let worker = MacClipboardConversionWorker(queue: queue, encodeImage: { _ in
            preconditionFailure("Ineligible snapshots must never invoke the image encoder")
        })
        for excluded in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutogeneratedType", "com.agilebits.onepassword", "com.agilebits.onepassword.private"] {
            worker.submit(snapshot(1, types: ["public.tiff", excluded]), hasDestination: true, completion: state.record)
        }
        worker.submit(snapshot(2), hasDestination: false, completion: state.record)
        queue.sync {}
        precondition(state.results.isEmpty)
    }
    static func onlyLatestPendingSnapshotIsConverted() {
        let queue = DispatchQueue(label: "clipboard.spec.latest"), state = State()
        let entered = DispatchSemaphore(value: 0), release = DispatchSemaphore(value: 0)
        let worker = MacClipboardConversionWorker(queue: queue, encodeImage: { image in
            precondition(!Thread.isMainThread, "Image conversion must stay off the main thread")
            guard case let .encoded(data) = image else { preconditionFailure() }
            let occurrence = Int(data[0]); state.lock.withLock { state.encoded.append(occurrence) }
            if occurrence == 1 { entered.signal(); precondition(release.wait(timeout: .now() + 5) == .success) }
            return Data([UInt8(occurrence)])
        })
        worker.submit(snapshot(1), hasDestination: true, completion: state.record)
        precondition(entered.wait(timeout: .now() + 5) == .success)
        for occurrence in 2...100 { worker.submit(snapshot(occurrence), hasDestination: true, completion: state.record) }
        release.signal(); queue.sync {}
        precondition(state.encoded == [1, 100], "A burst must keep only the active and latest pending snapshot")
        precondition(state.results.map(\.occurrence) == [100], "An old in-flight conversion must not publish")
        precondition(state.results.first?.candidate.content == Data([100]))
    }
    static func invalidOccurrenceSupersedesActiveWork() {
        let queue = DispatchQueue(label: "clipboard.spec.invalid"), state = State()
        let entered = DispatchSemaphore(value: 0), release = DispatchSemaphore(value: 0)
        let worker = MacClipboardConversionWorker(queue: queue, encodeImage: { _ in
            entered.signal(); precondition(release.wait(timeout: .now() + 5) == .success); return Data([1])
        })
        worker.submit(snapshot(1), hasDestination: true, completion: state.record)
        precondition(entered.wait(timeout: .now() + 5) == .success)
        worker.submit(snapshot(2, types: ["org.nspasteboard.ConcealedType"]), hasDestination: true, completion: state.record)
        release.signal(); queue.sync {}
        precondition(state.results.isEmpty, "A newer excluded occurrence must fence the older eligible conversion")
    }
    static func queuedCompletionHasAnAdmissionFence() {
        let queue = DispatchQueue(label: "clipboard.spec.result"), state = State()
        let worker = MacClipboardConversionWorker(queue: queue, encodeImage: { _ in Data([1]) })
        worker.submit(snapshot(1), hasDestination: true, completion: state.record)
        queue.sync {}
        precondition(state.results.count == 1 && worker.isCurrent(state.results[0]))
        worker.invalidate()
        precondition(!worker.isCurrent(state.results[0]), "A completion queued to MainActor must be rejected after supersession")
    }
    static func shutdownDropsActiveAndPendingWork() {
        let queue = DispatchQueue(label: "clipboard.spec.stop"), state = State()
        let entered = DispatchSemaphore(value: 0), release = DispatchSemaphore(value: 0)
        let worker = MacClipboardConversionWorker(queue: queue, encodeImage: { _ in
            entered.signal(); precondition(release.wait(timeout: .now() + 5) == .success); return Data([1])
        })
        worker.submit(snapshot(1), hasDestination: true, completion: state.record)
        precondition(entered.wait(timeout: .now() + 5) == .success)
        worker.submit(snapshot(2), hasDestination: true, completion: state.record)
        worker.stop(); release.signal(); queue.sync {}
        worker.submit(snapshot(3), hasDestination: true, completion: state.record); queue.sync {}
        precondition(state.results.isEmpty)
    }
    static func imagePixelsAndPayloadPolicySurviveConversion() {
        let image = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8,
            samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 8, bitsPerPixel: 32)!
        let pixels: [UInt8] = [255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 91, 123, 217, 255]
        pixels.withUnsafeBufferPointer { image.bitmapData!.update(from: $0.baseAddress!, count: pixels.count) }
        let tiff = image.representation(using: .tiff, properties: [:])!
        let png = MacClipboardImageEncoder.pngData(from: .encoded(tiff))!
        let decoded = NSBitmapImageRep(data: png)!
        precondition(decoded.pixelsWide == 2 && decoded.pixelsHigh == 2)
        for y in 0..<2 { for x in 0..<2 {
            var actual = [Int](repeating: 0, count: 4)
            decoded.getPixel(&actual, atX: x, y: y)
            let index = (y * 2 + x) * 4
            precondition(actual == pixels[index..<index + 4].map(Int.init), "TIFF conversion must preserve exact pixels")
        } }
        precondition(MacClipboardImageEncoder.pngData(from: .png(png)) == png, "Native PNG must remain byte-for-byte unchanged")
        let queue = DispatchQueue(label: "clipboard.spec.policy"), state = State()
        let worker = MacClipboardConversionWorker(queue: queue)
        worker.submit(.init(occurrence: 1, pasteboardTypes: ["public.tiff"], text: "fallback", image: .encoded(tiff)), hasDestination: true, completion: state.record)
        queue.sync {}
        precondition(state.results.count == 1 && state.results[0].candidate.kind == .png)
        precondition(state.results[0].candidate.scrcpyText == nil)
        worker.submit(.init(occurrence: 2, pasteboardTypes: ["public.png"], text: "fallback", image: .png(Data(repeating: 1, count: 4 * 1024 * 1024 + 1))), hasDestination: true, completion: state.record)
        queue.sync {}
        precondition(state.results.count == 1, "Oversized PNG must not fall back to text")
        worker.submit(.init(occurrence: 3, pasteboardTypes: ["public.url"], text: "https://example.com", image: nil), hasDestination: true, completion: state.record)
        queue.sync {}
        precondition(state.results.last?.candidate.kind == .url)
    }
}
